<?php
declare(strict_types=1);
require __DIR__ . '/bootstrap.php';
use humhub\modules\matcherIdeas\adapters\memory\{InMemoryIdeaRepository, InMemoryNativeRelations, InMemoryCurrentSpaceAccess};
use humhub\modules\matcherIdeas\application\{IdeaService, IdeaDraftService, IdeaRelationSource};
use humhub\modules\matcherIdeas\domain\IdeaContent;

$repo = new InMemoryIdeaRepository();
$native = new InMemoryNativeRelations();
$native->activeUsers = [1, 2, 3, 4, 5];
$native->memberships = [10 => [1, 2, 3], 20 => [1, 2, 4]];
$spaces = new InMemoryCurrentSpaceAccess(); $spaces->selected = [1 => 10, 2 => 10, 3 => 10, 4 => 20, 5 => 10];
$ideas = new IdeaService($repo, $native, $spaces);
$drafts = new IdeaDraftService($repo, $native);
$source = new IdeaRelationSource($repo, $native, $spaces);

rejects(fn() => new IdeaContent('', 'summary'), 'IDEA_VALIDATION_FAILED');
rejects(fn() => new IdeaContent('title', ''), 'IDEA_VALIDATION_FAILED');
rejects(fn() => new IdeaContent(str_repeat('中', 161), 'summary'), 'IDEA_VALIDATION_FAILED');
rejects(fn() => new IdeaContent('title', str_repeat('中', 2001)), 'IDEA_VALIDATION_FAILED');
rejects(fn() => new IdeaContent('title', "bad\0text"), 'IDEA_VALIDATION_FAILED');
rejects(fn() => $drafts->start(0), 'IDEA_ACCESS_DENIED');
$draft = $drafts->start(1, null, ['title' => '正式想法', 'summary' => '正式简介'], 'PRIVATE SYNTHETIC RAW TEXT');
check($draft['status'] === 'editing' && $draft['version'] === 1, 'new draft private and versioned');
check($repo->ideas === [] && $repo->activities === [], 'draft does not publish formal content or a Space');
rejects(fn() => $drafts->read(2, $draft['id']), 'IDEA_DRAFT_NOT_FOUND');
rejects(fn() => $drafts->update(2, $draft['id'], 1, []), 'IDEA_DRAFT_NOT_FOUND');
rejects(fn() => $drafts->confirm(2, $draft['id'], 1), 'IDEA_DRAFT_NOT_FOUND');
rejects(fn() => $drafts->update(1, $draft['id'], 2, []), 'IDEA_VERSION_CONFLICT');
rejects(fn() => $drafts->start(1, null, ['message_id' => 'not allowed']), 'IDEA_VALIDATION_FAILED');
rejects(fn() => $drafts->start(1, null, ['title' => []]), 'IDEA_VALIDATION_FAILED');
rejects(fn() => $drafts->start(1, null, [], str_repeat('x', 20001)), 'IDEA_VALIDATION_FAILED');
$draft = $drafts->update(1, $draft['id'], 1, ['title' => '正式标题']);
check($draft['version'] === 2 && $draft['fields']['summary'] === '正式简介', 'draft patch preserves existing summary');
$confirmed = $drafts->confirm(1, $draft['id'], 2); $ideaId = $confirmed['idea_id'];
check($confirmed['version'] === 1 && $confirmed['draft_version'] === 3, 'explicit confirmation saves a versioned idea');
check($repo->activities === [] && $repo->bindings === [], 'confirmation never publishes or binds');
check(!str_contains(json_encode($drafts->listOwned(1)), 'PRIVATE SYNTHETIC'), 'formal list excludes raw draft text');
rejects(fn() => $drafts->confirm(1, $draft['id'], 2), 'IDEA_VERSION_CONFLICT');
rejects(fn() => $drafts->update(1, $draft['id'], 3, ['title' => 'late']), 'IDEA_VERSION_CONFLICT');
check($drafts->listOwned(2)['items'] === [], 'private owner list filters by creator');
$editA = $drafts->start(1, $ideaId); $editB = $drafts->start(1, $ideaId);
$changed = $drafts->confirm(1, $editA['id'], 1, ['summary' => '正式确认简介']);
rejects(fn() => $drafts->confirm(1, $editB['id'], 1, ['summary' => 'stale']), 'IDEA_VERSION_CONFLICT');
check($repo->draft($editB['id'])['status'] === 'editing', 'stale base version leaves private draft editable');
check($repo->idea($ideaId)['summary'] === '正式确认简介', 'stale confirmation cannot overwrite current idea');
rejects(fn() => $ideas->associateSpace(2, $ideaId, 2, 10), 'IDEA_NOT_FOUND');
rejects(fn() => $ideas->associateSpace(1, $ideaId, 1, 10), 'IDEA_VERSION_CONFLICT');
rejects(fn() => $ideas->associateSpace(1, $ideaId, 2, 20), 'CURRENT_EVENT_MISMATCH');
$activity = $ideas->associateSpace(1, $ideaId, 2, 10); $activityId = $activity['id'];
check($activity['members_visible'] === false && $activity['message_id'] === null && $activity['status'] === 'published', 'publish defaults hidden and creates no conversation');
rejects(fn() => $ideas->associateSpace(1, $ideaId, 2, 10), 'IDEA_ACTIVITY_EXISTS');
$native->conversations[100] = ['id' => 100, 'creator_id' => 1, 'participant_ids' => [1, 2], 'title' => 'CHAT TITLE MUST NEVER BE USED', 'body' => 'PRIVATE CHAT BODY'];
$beforeConversations = $native->conversations;
rejects(fn() => $ideas->bindConversation(2, $activityId, 1, 100), 'IDEA_NOT_FOUND');
$native->conversations[101] = ['id' => 101, 'creator_id' => 2, 'participant_ids' => [1, 2]];
rejects(fn() => $ideas->bindConversation(1, $activityId, 1, 101), 'IDEA_CONVERSATION_DENIED');
$native->conversations[102] = ['id' => 102, 'creator_id' => 1, 'participant_ids' => [2]];
rejects(fn() => $ideas->bindConversation(1, $activityId, 1, 102), 'IDEA_CONVERSATION_DENIED');
$native->conversations[103] = ['id' => 103, 'creator_id' => 1, 'participant_ids' => [1, 4]];
rejects(fn() => $ideas->bindConversation(1, $activityId, 1, 103), 'IDEA_SPACE_DENIED');
check($repo->bindings === [], 'failed bindings create no record');
$activity = $ideas->bindConversation(1, $activityId, 1, 100);
check($activity['version'] === 2 && $activity['message_id'] === 100, 'explicit valid binding increments version');
check($native->conversations[100] === $beforeConversations[100], 'binding does not mutate native conversation or participants');
check($source->readCandidates(3, 2, 10) === [], 'default false member display suppresses relation');
$activity = $ideas->setMemberVisibility(1, $activityId, 2, true);
$out = $source->readCandidates(3, 2, 10);
check(count($out) === 1 && $out[0]['title'] === '正式标题' && $out[0]['summary'] === '正式确认简介', 'nonparticipant viewer receives only formal published text');
check($out[0]['membership_role'] === 'participant' && !$out[0]['conversation_available'], 'same Space metadata access does not grant chat');
check($source->readCandidates(2, 1, 10)[0]['conversation_available'] === true, 'native participant retains actual chat availability');
check($source->readCandidates(3, 1, 10)[0]['membership_role'] === 'creator', 'creator role is separately derived');
check($source->readCandidates(3, 3, 10) === [], 'Space member or follower alone is not a discussion participant');
check(!str_contains(json_encode($out), 'CHAT') && !str_contains(json_encode($out), 'message_id'), 'source output contains no message title body or identifier');
check(array_keys($out[0]) === ['title','summary','href','event_id','idea_id','version','conversation_available','kind','id','membership_role'], 'source exact DTO whitelist');
check($source->detail(3, $ideaId, $activityId, 10)['conversation_available'] === false, 'published metadata detail permits nonparticipant without chat');
rejects(fn() => $source->detail(3, $ideaId + 1, $activityId, 10), 'IDEA_NOT_FOUND');
rejects(fn() => $source->readCandidates(4, 2, 10), 'CURRENT_EVENT_MISMATCH');
rejects(fn() => $source->readCandidates(5, 2, 10), 'IDEA_RELATIONS_DENIED');
rejects(fn() => $source->readCandidates(3, 4, 10), 'IDEA_RELATIONS_DENIED');
$native->blocked = [[3, 2]];
rejects(fn() => $source->readCandidates(3, 2, 10), 'IDEA_RELATIONS_DENIED');
$native->blocked = [[3, 1]];
check($source->readCandidates(3, 2, 10) === [], 'blocked author suppresses object metadata');
$native->blocked = [];
$native->conversations[100]['participant_ids'][] = 4;
check($source->readCandidates(3, 2, 10) === [], 'new foreign Space participant revokes relation immediately');
$native->conversations[100]['participant_ids'] = [1, 2];
$native->memberships[10] = [1, 3];
rejects(fn() => $source->readCandidates(3, 2, 10), 'IDEA_RELATIONS_DENIED');
check($source->readCandidates(3, 1, 10) === [], 'remaining owner relation suppressed when another participant leaves Space');
$native->memberships[10] = [1, 2, 3];
$native->conversations[100]['participant_ids'] = [1];
check($source->readCandidates(3, 2, 10) === [], 'native leave removes owner participation immediately');
$native->conversations[100]['participant_ids'] = [2];
check($source->readCandidates(3, 2, 10) === [], 'creator departure suppresses binding metadata');
$native->conversations[100]['participant_ids'] = [1, 2];
$native->conversations[100]['creator_id'] = 2;
check($source->readCandidates(3, 2, 10) === [], 'creator mismatch invalidates bound conversation');
$native->conversations[100]['creator_id'] = 1;
$held = $native->conversations[100]; unset($native->conversations[100]);
check($source->readCandidates(3, 2, 10) === [], 'deleted Messenger conversation does not reveal stale metadata');
$native->conversations[100] = $held;
$activity = $ideas->updatePublication(1, $activityId, $activity['version'], null, 'archived');
check($source->readCandidates(3, 2, 10) === [], 'Space publication archive immediately revokes relation');
rejects(fn() => $source->detail(3, $ideaId, $activityId, 10), 'IDEA_NOT_FOUND');
rejects(fn() => $ideas->updatePublication(1, $activityId, $activity['version'] - 1, null, 'published'), 'IDEA_VERSION_CONFLICT');
$activity = $ideas->updatePublication(1, $activityId, $activity['version'], null, 'published');
check(count($source->readCandidates(3, 2, 10)) === 1, 'explicit re-publication restores eligible metadata');
$activity = $ideas->setMemberVisibility(1, $activityId, $activity['version'], false);
check($source->readCandidates(3, 2, 10) === [], 'member display off immediately revokes relation');
$activity = $ideas->setMemberVisibility(1, $activityId, $activity['version'], true);
$spaces->selected[1] = 20;
$second = $ideas->associateSpace(1, $ideaId, 2, 20);
rejects(fn() => $ideas->bindConversation(1, $second['id'], 1, 100), 'IDEA_CONVERSATION_ALREADY_BOUND');
check($second['space_id'] === 20 && $repo->activity($activityId)['space_id'] === 10, 'same long term idea uses separate Space records');
$spaces->selected[1] = 10;
rejects(fn() => $ideas->bindConversation(1, $activityId, $activity['version'], 101), 'IDEA_CONVERSATION_ALREADY_BOUND');
$ideas->setStatus(1, $ideaId, 2, 'archived');
check($source->readCandidates(3, 2, 10) === [], 'archived formal idea is absent from summaries');
rejects(fn() => $drafts->start(1, $ideaId), 'IDEA_NOT_FOUND');
$ideas->setStatus(1, $ideaId, 3, 'active');
check(count($source->readCandidates(3, 2, 10)) === 1, 'restored active idea remains correctly bound');

// Bounded complete-set scan must fail rather than silently truncate or fetch another Space.
for ($id = 3; $id <= 2002; ++$id) {
    $repo->activities[$id] = ['id' => $id, 'idea_id' => $ideaId, 'space_id' => 10, 'members_visible' => false, 'status' => 'published', 'message_id' => 100 + $id, 'version' => 1];
}
rejects(fn() => $source->readCandidates(3, 2, 10), 'IDEA_RELATIONS_LIMIT_EXCEEDED');
echo json_encode(['suite' => 'matcher-ideas-memory', 'checks' => count($checks), 'passed' => true, 'llm_calls' => 0, 'native_writes' => 0], JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE) . PHP_EOL;
