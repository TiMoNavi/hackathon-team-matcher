#!/usr/bin/env python3
"""Local-only HumHub preview lifecycle. Credentials are generated locally, never printed."""
from pathlib import Path
import argparse, json, os, secrets, signal, socket, subprocess, sys, time
ROOT=Path(__file__).resolve().parents[1]
RUN=ROOT/'.runtime'; PREFIX=RUN/'php-mysql'; LOG=RUN/'logs'; PORT=8090
PHP=PREFIX/'bin/php'; MYSQL=PREFIX/'bin/mysql'; MYSQLD=PREFIX/'bin/mysqld'
os.environ['PHPRC']=str(RUN/'php.ini')

def write_private(path,text):
 path.write_text(text);path.chmod(0o600)

def credentials():
 RUN.mkdir(mode=0o700,exist_ok=True);LOG.mkdir(exist_ok=True)
 path=RUN/'preview-credentials.json'
 if not path.exists():
  data={'admin_username':'admin','admin_email':'admin@localhost.test','admin_password':secrets.token_urlsafe(24),'db_name':'humhub_preview','db_user':'humhub_preview','db_password':secrets.token_urlsafe(32),'db_root_password':secrets.token_urlsafe(32),'cookie_key':secrets.token_hex(32),'rest_api_key':secrets.token_hex(32),'demo_password':secrets.token_urlsafe(24)}
  write_private(path,json.dumps(data,indent=2)+'\n')
 return json.loads(path.read_text())

def configure():
 c=credentials();ext=subprocess.check_output([str(PREFIX/'bin/php-config'),'--extension-dir'],text=True).strip()
 ini='\n'.join([f'extension_dir="{ext}"','extension=mysqlnd','extension=pdo_mysql','extension=gd','date.timezone=Asia/Shanghai','memory_limit=512M','upload_max_filesize=30M','post_max_size=35M','max_execution_time=120','display_errors=Off','log_errors=On',f'error_log="{LOG}/php-error.log"',f'session.save_path="{RUN}/sessions"','session.cookie_httponly=1','session.cookie_samesite=Lax',f'openssl.cafile="{PREFIX}/ssl/cacert.pem"',f'curl.cainfo="{PREFIX}/ssl/cacert.pem"'])+'\n'
 (RUN/'sessions').mkdir(mode=0o700,exist_ok=True);(RUN/'php.ini').write_text(ini)
 settings={
  'HUMHUB_DEBUG':'false','HUMHUB_CONFIG__TIME_ZONE':'Asia/Shanghai','HUMHUB_CONFIG__LANGUAGE':'zh-CN',
  'HUMHUB_CONFIG__COMPONENTS__DB__DSN':f'mysql:unix_socket={RUN}/mysql.sock;dbname={c["db_name"]}',
  'HUMHUB_CONFIG__COMPONENTS__DB__USERNAME':c['db_user'],'HUMHUB_CONFIG__COMPONENTS__DB__PASSWORD':c['db_password'],
  'HUMHUB_CONFIG__COMPONENTS__DB__CHARSET':'utf8mb4','HUMHUB_CONFIG__COMPONENTS__MAILER__USE_FILE_TRANSPORT':'true',
  'HUMHUB_WEB_CONFIG__COMPONENTS__REQUEST__COOKIE_VALIDATION_KEY':c['cookie_key'],
  'HUMHUB_WEB_CONFIG__COMPONENTS__REQUEST__HOST_INFO':f'http://127.0.0.1:{PORT}',
  'HUMHUB_CONFIG__COMPONENTS__URL_MANAGER__ENABLE_PRETTY_URL':'true',
  'HUMHUB_CONFIG__COMPONENTS__URL_MANAGER__SHOW_SCRIPT_NAME':'false',
 }
 env=ROOT/'.env';marker=RUN/'preview-managed-env'
 if env.exists() and not marker.exists():raise RuntimeError('Existing .env is not managed by this preview; refusing to replace it')
 write_private(env,'# Generated by deploy/preview.py; local preview only\n'+'\n'.join(k+'='+json.dumps(v) for k,v in settings.items())+'\n');marker.touch()
 write_private(RUN/'mysql-root.cnf','[client]\nuser=root\npassword='+c['db_root_password']+'\nsocket='+str(RUN/'mysql.sock')+'\n')
 return c

def pid_for(name):
 path=RUN/(name+'.pid')
 try:
  pid=int(path.read_text().strip());os.kill(pid,0)
  command=subprocess.check_output(['ps','-p',str(pid),'-o','command='],text=True)
  if str(ROOT) not in command:return None
  return pid
 except (ValueError,OSError,subprocess.CalledProcessError):return None

def start_mysql():
 if pid_for('mysql'):return
 data=RUN/'mysql';data.mkdir(mode=0o700,exist_ok=True)
 if not (data/'mysql').exists():
  with (LOG/'mysql-initialize.log').open('ab') as log:
   subprocess.run([str(MYSQLD),'--no-defaults',f'--basedir={PREFIX}',f'--lc-messages-dir={PREFIX}/share/mysql',f'--datadir={data}','--initialize-insecure'],check=True,stdout=log,stderr=log)
 args=[str(MYSQLD),'--no-defaults',f'--basedir={PREFIX}',f'--lc-messages-dir={PREFIX}/share/mysql',f'--datadir={data}',f'--socket={RUN}/mysql.sock',f'--pid-file={RUN}/mysql.pid',f'--log-error={LOG}/mysql.log','--skip-networking=ON','--mysqlx=0','--character-set-server=utf8mb4','--collation-server=utf8mb4_unicode_ci']
 with (LOG/'mysql-process.log').open('ab') as log:p=subprocess.Popen(args,cwd=ROOT,stdout=log,stderr=log,start_new_session=True)
 for _ in range(120):
  if p.poll() is not None:raise RuntimeError('MySQL did not start; inspect .runtime/logs/mysql.log')
  try:
   s=socket.socket(socket.AF_UNIX);s.connect(str(RUN/'mysql.sock'));s.close();return
  except OSError:time.sleep(.25)
 raise RuntimeError('MySQL startup timed out')

def setup_database(c):
 if (RUN/'database-ready').exists():return
 sql=f"CREATE DATABASE IF NOT EXISTS {c['db_name']} CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci; CREATE USER IF NOT EXISTS '{c['db_user']}'@'localhost' IDENTIFIED BY '{c['db_password']}'; GRANT ALL PRIVILEGES ON {c['db_name']}.* TO '{c['db_user']}'@'localhost'; ALTER USER 'root'@'localhost' IDENTIFIED BY '{c['db_root_password']}';"
 for opts in [[f'--defaults-extra-file={RUN}/mysql-root.cnf'],['--no-defaults',f'--socket={RUN}/mysql.sock','--user=root']]:
  result=subprocess.run([str(MYSQL),*opts,'--protocol=SOCKET'],input=sql,text=True,capture_output=True)
  if result.returncode==0:(RUN/'database-ready').touch();return
 raise RuntimeError('Local database provisioning failed; no SQL or credentials were printed')

def php(args,logname=None):
 cmd=[str(PHP),'-c',str(RUN/'php.ini'),*map(str,args)]
 if logname:
  with (LOG/logname).open('ab') as log:subprocess.run(cmd,cwd=ROOT,check=True,stdout=log,stderr=log)
 else:subprocess.run(cmd,cwd=ROOT,check=True)

def start_web():
 if pid_for('web'):return
 with socket.socket() as s:
  if s.connect_ex(('127.0.0.1',PORT))==0:raise RuntimeError(f'Port {PORT} is already in use; refusing to stop another service')
 with (LOG/'web.log').open('ab') as log:
  p=subprocess.Popen([str(PHP),'-c',str(RUN/'php.ini'),'-S',f'127.0.0.1:{PORT}','-t',str(ROOT),str(ROOT/'deploy/router.php')],cwd=ROOT,stdout=log,stderr=log,start_new_session=True)
 (RUN/'web.pid').write_text(str(p.pid))
 for _ in range(60):
  if p.poll() is not None:raise RuntimeError('PHP web server exited; inspect .runtime/logs/web.log')
  with socket.socket() as s:
   if s.connect_ex(('127.0.0.1',PORT))==0:return
  time.sleep(.1)
 raise RuntimeError('Web server startup timed out')

def start_background():
 services={
  'queue':[str(PHP),'-c',str(RUN/'php.ini'),str(ROOT/'protected/yii'),'queue/listen','1'],
  'scheduler':[sys.executable,str(ROOT/'deploy/scheduler.py')],
 }
 if (RUN/'profile-s6-installed').exists():
  services['profile-ai']=[str(PHP),'-c',str(RUN/'php.ini'),str(ROOT/'protected/yii'),'matcher-onboarding/ai-worker/watch','--limit=20','--interval=2']
 for name,command in services.items():
  if pid_for(name):continue
  with (LOG/(name+'.log')).open('ab') as log:
   process=subprocess.Popen(command,cwd=ROOT,stdout=log,stderr=log,start_new_session=True)
  (RUN/(name+'.pid')).write_text(str(process.pid))
  time.sleep(.15)
  if process.poll() is not None:raise RuntimeError(name+' exited; inspect local logs')

def stop():
 for name in ['web','profile-ai','scheduler','queue','mysql']:
  pid=pid_for(name)
  if pid:
   os.kill(pid,signal.SIGTERM)
   for _ in range(100):
    if not pid_for(name):break
    time.sleep(.1)
   if pid_for(name):raise RuntimeError(f'{name} is still stopping; not forcing a database kill')
  print(name+': stopped')

if __name__=='__main__':
 parser=argparse.ArgumentParser();parser.add_argument('command',choices=['init','start','stop','status','cron']);args=parser.parse_args()
 try:
  if args.command=='stop':stop()
  elif args.command=='status':print(json.dumps({'url':f'http://127.0.0.1:{PORT}','web_running':bool(pid_for('web')),'mysql_running':bool(pid_for('mysql')),'queue_running':bool(pid_for('queue')),'scheduler_running':bool(pid_for('scheduler')),'profile_ai_worker_running':bool(pid_for('profile-ai')),'database_initialized':(RUN/'database-ready').exists(),'application_initialized':(RUN/'humhub-ready').exists()},indent=2))
  else:
   c=configure();start_mysql();setup_database(c)
   if args.command=='init':php([ROOT/'deploy/bootstrap.php','install'],'humhub-install.log');(RUN/'humhub-ready').touch()
   elif not (RUN/'humhub-ready').exists():raise RuntimeError('Run deploy/preview.py init first')
   if args.command=='cron':php([ROOT/'protected/yii','cron/run'],'cron.log');php([ROOT/'protected/yii','queue/run'],'queue.log')
   else:start_web();start_background();print(f'Preview running: http://127.0.0.1:{PORT}');print('Credentials: backend/.runtime/preview-credentials.json (not printed)')
 except Exception as exc:
  print(type(exc).__name__+': '+str(exc),file=sys.stderr);sys.exit(1)
